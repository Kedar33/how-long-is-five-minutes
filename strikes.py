from __future__ import annotations

import json
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path


import numpy as np

from build_results import J5, Macros, pass1
from sums import cr1_from_sums, ratio_from_sums

MKT = Path("data/hist/mkt_strikes")
OUT = Path("out/numbers_strikes.tex")


def share(rows, weight="market"):
    a = np.array([r["a"][J5] / r["nh"][J5] for r in rows])
    t = a + np.array([(r["b"][J5] + r["c"][J5]) / r["nh"][J5] for r in rows])
    ev = np.array([r["event"] for r in rows])
    if weight == "event":
        _, inv, cnt = np.unique(ev, return_inverse=True, return_counts=True)
        w = 1.0 / cnt[inv]
    else:
        w = np.ones(len(rows))
    return ratio_from_sums(a * w, t * w, w, ev)


def calibration_gap(rows):

    gap = np.array([r["y"] - float(np.mean(r["cal_mid"])) for r in rows]) * 100
    return cr1_from_sums(gap, np.ones(gap.size), np.array([r["event"] for r in rows]))


def main() -> int:
    files = sorted(str(f) for f in MKT.glob("*.npz") if not f.name.endswith(".tmp.npz"))
    with ProcessPoolExecutor(max_workers=6) as pool:
        rows = [r for r in pool.map(pass1, files, chunksize=32) if r is not None and r["nh"][J5] > 0]
    main_tk = {m["ticker"] for m in json.loads(Path("data/hist/sample.json").read_text())["markets"]}
    events_with_main = {r["event"] for r in rows if r["ticker"] in main_tk}
    rows = [r for r in rows if r["event"] in events_with_main]

    M = Macros()
    M.int("StrEvents", len(events_with_main))
    M.int("StrMarkets", len(rows))
    for tag, want in (("Sp", True), ("NS", False)):
        grp = [r for r in rows if (r["cat"] == "Sports") == want]
        top = [r for r in grp if r["ticker"] in main_tk]
        rest = [r for r in grp if r["ticker"] not in main_tk]
        for lab, sel, w in (("Main", top, "market"), ("Other", rest, "event"), ("All", grp, "event")):
            m, se = share(sel, w)
            M.num(f"Str{tag}{lab}", m); M.num(f"Str{tag}{lab}SE", se)
        for lab, sel in (("Main", top), ("Other", rest)):
            m, se = calibration_gap(sel)
            M.num(f"Gap{tag}{lab}", m, "{:.1f}"); M.num(f"Gap{tag}{lab}SE", se, "{:.1f}")
        M.int(f"Str{tag}N", len(grp))
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("% generated by strikes.py\n" + "\n".join(M.lines) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
